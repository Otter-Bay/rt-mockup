#!/usr/bin/env python3
"""Writes js/card_meta.js: for each info card, the date it was added and last changed (from git history),
so the Ask "Source" panel can say when the information came in. Run from the repo root after editing card files:
    python3 tools/card_dates.py
"""
import re, subprocess, json, datetime

FILES = ["js/scales.js", "js/sleep_scales.js", "js/cna_scales.js", "js/acronyms.js"]
today = datetime.date.today().isoformat()

def git(*a):
    return subprocess.run(["git", *a], capture_output=True, text=True).stdout.strip()

meta = {}
for f in FILES:
    src = open(f, encoding="utf-8").read()
    keys = re.findall(r"^\s*([a-z0-9_]+): \{ (?:field: \"[a-z]+\", )?title", src, re.M)
    keys += re.findall(r'add\.(abbr_[a-z]+) = \{', src)
    for k in keys:
        pat = f"{k}: {{"
        added = git("log", "--reverse", "--format=%ad", "--date=short", "-S", pat, "--", f).split("\n")[0]
        meta[k] = {"added": added or today, "file": f}
# Glossary cards are built in a loop; date them from the file itself.
f = "js/acronyms.js"
first = git("log", "--reverse", "--format=%ad", "--date=short", "--", f).split("\n")[0] or today
last = git("log", "-1", "--format=%ad", "--date=short", "--", f) or today
for g in ["gas", "vent", "mode", "pft", "equip", "dx", "rx", "care"]:
    meta.setdefault("abbr_" + g, {"added": first, "file": f})
for g in ["rec", "stage", "peds", "resp", "move", "org"]:
    meta.setdefault("sabbr_" + g, {"added": today, "file": f})
for k, v in meta.items():
    # Last commit that touched this card's own lines (from "key: {" to its "src:" line); glossary cards use the file.
    rng = f"/^ *{k}: {{/,/src:/:{v['file']}"
    ch = git("log", "-1", "--format=%ad", "--date=short", "-L", rng).split("\n")[0] if not k.startswith(("abbr_", "sabbr_")) else ""
    if not re.match(r"\d{4}-\d\d-\d\d$", ch or ""):
        ch = git("log", "-1", "--format=%ad", "--date=short", "--", v["file"]) or today
    v["changed"] = ch
    if v["added"] > v["changed"]: v["changed"] = v["added"]
out = "/* Generated by tools/card_dates.py: when each info card was added and when its file last changed. Do not edit by hand. */\n"
out += "window.CARD_META = " + json.dumps(meta, indent=0, sort_keys=True) + ";\n"
open("js/card_meta.js", "w", encoding="utf-8").write(out)
print(len(meta), "cards")
